"""Собирает выжимку законки в один файл для вставки в обычный чат с ИИ.

Полный корпус (1771 фрагмент) в контекст чата не влезет, поэтому берём то,
на чём модель ошибается чаще всего и где ошибка дороже всего:
санкции статей УАК, порядок задержания, основания освобождения и позиции
Верховного суда. Остальное честно помечаем как отсутствующее.
"""
import io, os, re, json

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
OUT = os.path.join(HERE, "..", "МУРРИЕТА-ЗАКОНКА-ПРОМПТ.md")
OUT_MIN = os.path.join(HERE, "..", "МУРРИЕТА-ЗАКОНКА-ПРОМПТ-КОМПАКТ.md")
COMPACT = "--compact" in os.sys.argv

# Позиции ВС, которые чаще всего решают дело. Держим полностью, остальные —
# одной строкой: номер + тема, чтобы модель знала об их существовании.
KEY_ACTS = ["22", "355", "362", "428", "461", "468", "469", "534", "553", "568", "3086", "3100"]

# Что вытащить из ПК: (заголовок в файле, регэксп по heading секции)
PK_PICKS = [
    ("Задержание: основания",        r"Статья 1\. Задержание подозреваемого"),
    ("Задержание: порядок",          r"Статья 2\. Порядок задержания"),
    ("Вызов адвоката",               r"Статья 2\.1"),
    ("Субъекты задержания",          r"Статья 3\. Субъекты задержания"),
    ("Задержание госслужащего",      r"Статья 4\. Задержание государственных служащих"),
    ("Основания освобождения",       r"Статья 5\. Основания освобождения"),
    ("Расследование",                r"Статья 2\. Расследование"),
    ("Уведомление лиц",              r"Статья 10\. Процедура извещения"),
    ("Презумпция невиновности",      r"Статья 1\. Презумпция невиновности"),
    ("Недопустимые доказательства",  r"Статья 2\. Недопустимые доказательства"),
    ("Обязанность видеофиксации",    r"Статья 1\. Осуществление фото"),
    ("Сроки хранения фиксации",      r"Статья 2\. Сроки хранения"),
]


# Формулировки, которыми суд вводит правило, а не пересказывает обстоятельства.
RULE_SIGNALS = [
    (r"разъясня|следует понимать|надлежит понимать|разграничива", 5),
    (r"приходит к выводу|делает вывод", 4),
    (r"не является|не может быть|не допускается|недопустим", 4),
    (r"обязан(?:ность)?|вправе|подлежит", 3),
    (r"устанавливает,? что|исходит из того", 3),
    (r"таким образом|следовательно", 2),
]


def holding(text):
    """Операционная часть акта: ради неё он и нужен.

    Полные тексты решений весят под 160 тыс. символов на всю подборку и в
    контекст чата не влезают, а мотивировка суда там занимает 90% объёма.
    Берём «Разъяснение по прецеденту» либо резолютивную часть, иначе —
    последний кусок, где суд формулирует вывод."""
    t = text.strip()

    # «Разъяснение по прецеденту» — уже готовая выжимка от самого суда.
    limit = 900 if COMPACT else 3200
    i = t.find("Разъяснение по прецеденту")
    if i >= 0:
        part = t[i:].strip()
        return part if len(part) <= limit else part[:limit].rsplit("\n", 1)[0] + "\n[…]"

    if len(t) <= limit:
        return t

    # Обрезать по позиции нельзя: у прецедента №568 резолютивной части нет
    # вовсе, а правило о самостоятельных нарушениях задержанного стоит ровно
    # в середине текста. Поэтому отбираем абзацы, в которых суд формулирует
    # правило, и оставляем их в исходном порядке.
    para = [p.strip() for p in re.split(r"\n{2,}", t) if len(p.strip()) > 80]
    kept, budget = [], (900 if COMPACT else 4600)
    for i, p in enumerate(para):
        score = 0
        for pat, val in RULE_SIGNALS:
            if re.search(pat, p, re.I):
                score += val
        if i >= len(para) - 3:      # выводы почти всегда в конце
            score += 2
        if score:
            kept.append((score, i, p))
    kept.sort(key=lambda x: (-x[0], x[1]))
    chosen, used = [], 0
    for score, i, p in kept:
        if used + len(p) > budget:
            continue
        chosen.append((i, p)); used += len(p)
    if not chosen:
        return "[…начало опущено…]\n" + t[-3000:].split("\n", 1)[-1]
    chosen.sort()
    return "[…приведены ключевые положения акта…]\n" + "\n\n".join(p for _, p in chosen)


def load(name):
    return json.load(io.open(os.path.join(DATA, name), encoding="utf-8"))


def pk_sections():
    d = load("docs/pk.json")
    out = []
    for label, pat in PK_PICKS:
        for s in d["sections"]:
            h = s.get("heading") or ""
            if re.search(pat, h):
                body = "\n".join(s.get("paras", []))
                if body.strip():
                    out.append((label, h, body))
                break
    return out


def main():
    arts = load("articles.json")
    dk = load("traffic.json")
    prec = load("precedents.json")
    L = []
    w = L.append

    w("# ЗАКОНОДАТЕЛЬСТВО ШТАТА САН-АНДРЕАС — Murrieta (Сервер №20), GTA 5 RP")
    w("")
    w("Ты — правовой помощник по законодательству этого сервера. Ниже выжимка")
    w("действующей редакции. Отвечай СТРОГО по ней.")
    w("")
    w("## ЖЁСТКИЕ ПРАВИЛА")
    w("")
    w("1. Санкции, суммы, залоги и сроки бери ТОЛЬКО из этого файла. Если статьи")
    w("   здесь нет — прямо скажи «в этой выжимке такой статьи нет», не выдумывай.")
    w("2. Проверяй диспозицию буквально против фактов. Не хватает элемента состава —")
    w("   статья не подходит, даже если «по смыслу похоже». Назови недостающий элемент.")
    w("3. ПРОВЕРЯЙ СУБЪЕКТ. Часть статей применима не к любому: помечены строкой")
    w("   СУБЪЕКТ. Статья «для гражданского лица» к сотруднику не применяется НИКОГДА,")
    w("   и наоборот. Это самая частая и самая дорогая ошибка.")
    w("4. Толкования и прецеденты Верховного суда обязательны и имеют силу закона.")
    w("   При расхождении буквы статьи и акта ВС — решает акт ВС.")
    w("5. Правила проекта (OOC) сильнее кодексов штата (IC). Если кодекс разрешает,")
    w("   а правила запрещают — ответ «нельзя».")
    w("6. Различай уголовные [У] и административные [А] статьи: от этого зависит")
    w("   и подсудность, и сама допустимость задержания.")
    w("7. Не начинай ответ с «Можно/Нельзя», если вопрос не является запросом")
    w("   разрешения. На «что такое», «объясни», «какие принципы» отвечай по существу.")
    w("8. Перевод IC→OOC: 1 год = 30 минут, 1 сутки = 1 минута.")
    w("")
    w("СОКРАЩЕНИЯ: УАК — Уголовно-административный кодекс · ПК — Процессуальный ·")
    w("ДК — Дорожный · СК — Судебный · ТК — Трудовой · ЭК — Этический ·")
    w("ЗОТ — закон о закрытых и охраняемых территориях · КПЗ/ФТ — места содержания.")
    w("")

    # ---------------- УАК
    w("## СТАТЬИ УАК (%d)" % len(arts))
    w("")
    w("Формат: номер [тип] название — САНКЦИЯ | залог | доп. пометки")
    w("Тип: У — уголовная, А — административная. Звёзды: * 7 дней запрета на")
    w("госслужбу, ** 21 день, *** пожизненно.")
    w("")
    cur = ""
    for a in arts:
        if a.get("chapter") and a["chapter"] != cur:
            cur = a["chapter"]
            w("")
            w("### " + cur)
        line = "%s [%s]%s %s — %s" % (
            a["num"], a["type"], "*" * a.get("ban", 0),
            a["title"].strip(), a["sanction"].strip() or "санкция не указана")
        if a.get("bail"):
            line += " | залог %s$" % format(a["bail"], ",d").replace(",", ".")
        w(line)
        for pat, note in (
            (r"гражданск(?:им|ое)\s+лиц", "ТОЛЬКО гражданское лицо, к сотруднику НЕ применяется"),
            (r"должностн(?:ым|ое)\s+лиц", "ТОЛЬКО должностное лицо"),
            (r"лицом,?\s+являющимся\s+сотрудником|сотрудником\s+государственной\s+структуры,\s+представителем",
             "ТОЛЬКО сотрудник госструктуры или представитель судебной власти"),
            (r"судьей|судьёй", "ТОЛЬКО судья"),
            (r"работодателем", "ТОЛЬКО работодатель или уполномоченное им лицо"),
        ):
            if re.search(pat, a["title"], re.I):
                w("    СУБЪЕКТ: " + note)
                break
        if not COMPACT:
            for n in a.get("notes", [])[:2]:
                w("    " + n.strip()[:300])
    w("")

    # ---------------- ДК
    w("## СТАТЬИ ДОРОЖНОГО КОДЕКСА (%d)" % len(dk))
    w("")
    w("Все наказания по ДК — административные.")
    w("")
    for a in dk:
        if COMPACT and not (a.get("sanction") or "").strip():
            continue
        w("%s %s — %s" % (a["num"], a["title"].strip(), (a.get("sanction") or "без наказания").strip()))
    w("")

    # ---------------- ПК
    w("## ПРОЦЕССУАЛЬНЫЙ КОДЕКС — ключевые нормы")
    w("")
    for label, head, body in pk_sections():
        w("### %s (%s)" % (label, head.strip()))
        w(body.strip())
        w("")

    # ---------------- акты ВС
    active = [x for x in prec["items"] if x["active"]]
    w("## АКТЫ ВЕРХОВНОГО СУДА (%d действующих)" % len(active))
    w("")
    w("Обязательны к применению, имеют силу закона. Приведена операционная часть")
    w("каждого акта — разъяснение или резолютивная часть; мотивировка опущена.")
    w("")
    for x in active:
        if x.get("text"):
            w("### %s №%s — %s" % (x["kind"], x["num"], x.get("topic", "")))
            if x.get("date"):
                w("Дата: %s. Стороны: %s" % (x["date"], x.get("parties", "—")))
            w("")
            w(holding(x["text"]))
            w("")
    no_text = [x for x in active if not x.get("text")]
    if no_text:
        w("### Акты без текста в выжимке (известны только по теме)")
        for x in no_text:
            w("- %s №%s — %s" % (x["kind"], x["num"], x.get("topic") or x.get("parties", "")))
        w("")

    # ---------------- навигация
    if prec.get("nav"):
        w("## КАКИЕ СТАТЬИ УЖЕ РАЗЪЯСНЕНЫ")
        w("")
        cur = ""
        for n in prec["nav"]:
            if n["doc"] != cur:
                cur = n["doc"]
                w("")
                w("**%s**" % re.sub(r"^[^\w]+", "", cur))
            w("- %s → %s" % (n["subject"], ", ".join("№" + a for a in n["acts"])))
        w("")

    w("## ЧЕГО В ЭТОЙ ВЫЖИМКЕ НЕТ")
    w("")
    w("Полных текстов кодексов и законов, уставов фракций, правил проекта и")
    w("дополнений Murrieta, а также большинства актов ВС целиком. Если вопрос")
    w("упирается в них — так и скажи и отправь к первоисточнику:")
    w("полная база с поиском и ИИ — https://zakonka.online")
    w("форум — https://forum.gta5rp.com/forums/zakonodatel-naya-baza.1732/")

    txt = "\n".join(L) + "\n"
    path = OUT_MIN if COMPACT else OUT
    io.open(path, "w", encoding="utf-8").write(txt)
    print("файл: %s" % os.path.normpath(path))
    print("размер: %d символов (~%d тыс. токенов)" % (len(txt), len(txt) // 3 // 1000))
    print("статей УАК: %d | статей ДК: %d | актов ВС: %d (полных: %d)"
          % (len(arts), len(dk), len(active),
             len([x for x in active if x["num"] in KEY_ACTS and x.get("text")])))


if __name__ == "__main__":
    main()
